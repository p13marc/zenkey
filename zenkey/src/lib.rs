//! The zk2 runtime: the session half of zk2 (#610 onward).
//!
//! Everything that needs no session (keys, contracts, bundles, the
//! descriptor check, the error envelope) is `zenkey-model`'s, re-exported
//! here as [`model`]. This crate adds what a Zenoh session does with them,
//! rule by rule from the spec (`spec/core.md`):
//!
//! | Module | Spec |
//! |---|---|
//! | [`config`]: what a deployment configures | §1.5, §3.2 R1–R2, §8.1 (the tokenless set) |
//! | [`hostid`]: a system minted from the machine id, once per run | `hostid.v1` §2.3–§2.8, §2.13 |
//! | [`service`]: bring-up, the descriptor, tokens, epochs, members | §1.5, §3.3, §8.1–§8.2 |
//! | [`presence`]: reading tokens and descriptors | §8.1 |
//! | [`retrieval`]: fetching a contract bundle | §8.4 |
//! | [`writer`]: the contract's QoS and `Encoding` on every sample; events | §2.4–§2.6, §7.2 |
//! | [`budget`]: a new member refused at the bound, an occurrence beyond the rate (#741) | §2.7 |
//! | [`telemetry`]: a metric's writer refuses what `telemetry.v1` forbids, and writes the epoch: the instance's, or a member's | `telemetry.v1` §2.6–§2.9; §1.5, §8.1 |
//! | [`qos`]: the contract's QoS as zenoh spells it | §2.4 |
//! | [`consumer`]: data through a role's bindings | §3.2 R1–R7 |
//! | [`operation`]: serving calls; [`client`]: calling them, one address or a fleet; [`ownership`]: the split-brain diagnosis | §5.1 O1–O7, §5.2, §6 |
//! | [`call`]: what a handler receives and a caller gets back, without a session | §5.1 O3, O5–O7, §5.2 |
//! | [`shm`]: the memlock limit SHM falls back under | §7.4 |
//! | [`state`]: stamped mutations, tombstones, clocks, the owner-only GET | §4.1–§4.3, S1–S4, S6–S7 |
//! | [`health`]: `health.v1`'s owner, its standard contract embedded: the status, checks and faults; `clock_ahead` | `health.v1` §2.2–§2.6, §2.10; §4.3, §8.2 |
//! | [`alarms`]: `alarms.v1`'s owner, its standard contract embedded: the acts keyed by the recipe, confirmations every 450 s, the bound, adoption at a restart from the owner's record or an archive | `alarms.v1` §2.1–§2.9; §2.7, §4.3, §4.4 |
//! | [`config_v1`]: `config.v1`'s owner, its standard contract embedded: the five operations over a device, the view and the status, the change events, the deadline timer, the persisted layer, desired state | `config.v1` §2.1–§2.19; §2.6–§2.7, §5, §8.2 |
//! | [`desired`]: `desired.v1`'s author and target: documents put only on a change and again at a restart from the author's record; the target's subscription, seeds, last-known read, acts on the application's handler and report; `config.v1` as a target | `desired.v1` §2.2–§2.16; §4.2, §4.4, §8.1 |
//! | [`redundancy`]: `redundancy.v1`'s candidate: the claim, the reads on a session of their own, the watch, the acts of an [`zenkey_model::redundancy::Elector`]: a governed interface's resources declared only while it serves, its writes refused while it stands by | `redundancy.v1` §2.2–§2.14; §6, §8.1–§8.2 |
//! | [`archive`]: last-known state, recorded and aligned; the explicit read | §4.4, S5–S6 |
//! | [`codec`]: a Rust type and how it is carried; [`typed`]: the handles generated code is written against (#611) | §7.2 |
//!
//! **Zenoh stays reachable.** The runtime never owns the session: a
//! service holds a clone, every key is available as a key expression, and
//! raw resources are plain zenoh publishers and queryables declared with the
//! contract's QoS. The typed layers (streams #619, state #620, operations
//! #621, codegen #611) are built on these.
//!
//! **The `zenoh` feature** (default) is everything that holds a session.
//! Without it, this crate is the model, [`config`], [`Implementation`],
//! [`call`] and [`codec`]: what a contract crate generated by `zenkey-build`
//! needs for its types and its `Handlers`/`Api` traits, with no zenoh
//! dependency beyond `zenoh-keyexpr` (#611). **The `hostid` feature**, which
//! `zenoh` turns on, is `hostid.v1`'s runtime: it reads the host and holds no
//! session, so a tool can mint without one (#719).
//!
//! **The profiles' owner halves** (`spec/profiles/`): `hostid.v1` is
//! [`hostid`]; `freshness.v1` is the [`state`] writers' refresher (#720);
//! `health.v1` is [`health`], through [`ServiceBuilder::health`] (#721): the
//! status never better than its worst check, put before the tokens and
//! confirmed every 30 s, checks on change, faults, and `clock_ahead` while
//! the clock guard holds; `config.v1` is [`config_v1`], through
//! [`ServiceBuilder::config_v1`] (#768): `zenkey_model::config`'s owner
//! wrapped over the application's device, its acts, timer, persisted layer
//! and puts. The module is `config_v1`, the profile's id as a path, because
//! [`config`] is the deployment's configuration; `alarms.v1` is [`alarms`],
//! through [`ServiceBuilder::alarms`] (#800): each act keyed by
//! `zenkey_model::alarms`'s recipe and put whole, each firing alarm
//! confirmed every 450 s until the owner stops evaluating it, a raise past
//! the bound refused, and a restart's adoption from the application's
//! record, else an archive on its own side, before anything is alive;
//! `telemetry.v1` is [`telemetry`] (#819): every writer of a metric resource
//! checks each sample against its declaration, refuses a counter or
//! histogram that goes down within its epoch, and writes the epoch a reader
//! reads (the instance id, or a member's epoch) where the application left
//! it out; `desired.v1` is [`desired`] (#840): an author's documents,
//! put on a content change only and again from its record at a restart,
//! through [`ServiceBuilder::desired_author`], and a target's role,
//! subscribed, seeded at start and whenever its author appears, read from
//! an archive with its author absent, and acted on once per version through
//! the application's handler, through [`ServiceBuilder::desired_target`]
//! (`config.v1`'s owner through [`ServiceBuilder::desired_config`]);
//! `redundancy.v1` is [`redundancy`] (#841): through
//! [`ServiceBuilder::redundancy`], every governed interface the service
//! implements is claimed at its start (its descriptor marking it standby,
//! the instance token), followed on a watch session, read on a reader of
//! its own, and elected by `zenkey_model::redundancy`'s `Elector`; each of
//! its resources is declared only while the instance serves it, a write
//! while it stands by is refused, a takeover runs core §8.2's steps and a
//! step-down their reverse, and `external` serves only with the
//! application's lock; `timing.v1` is [`timing`] (#908): a consumer's
//! subscription to a timed stream carries each arrival's instant and stamp
//! in its [`consumer::Delivery`], judges each provider's members' deadline
//! with `zenkey_model::timing`'s tracker, on a one-shot timer, its owners'
//! presence followed on a watch session handed in, and discards a sample
//! that arrives expired on the binding's stated clock bound; a writer of a
//! stream declaring a lifespan stamps each put from the service's clock.

